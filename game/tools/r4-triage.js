#!/usr/bin/env node
// Round 4 triage table generator (D5 QA). Docs only: reads game/design/beta/*-r2.json (every item that is not FIXED) and the hand-kept
// overlay game/design/beta/round4-status.json, writes game/design/beta/ROUND4-TRIAGE.md.
//   node game/tools/r4-triage.js            regenerate the table
//   node game/tools/r4-triage.js --check    exit 1 when an r2 item has no overlay entry or the overlay names an unknown id
// Overlay entry: "<id>": { "owner": "D1".."D5", "status": "open|claimed|verified|decided|backlog", "test": "file or -", "note": "..." }
// Status rules (ROUND4.md): "verified" = D5 replayed it functionally (test named, fails before / passes after, or a manual replay
// named in the note); "claimed" = a fix commit exists but D5 has not replayed it; "decided" = closed by an owner decision or a
// documented won't-do (off-limits file, backlog by ROUND4.md); "backlog" = P3 that ROUND4.md moves out of the round; "open" = no fix yet.
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'design', 'beta');
const overlayPath = path.join(dir, 'round4-status.json');
const overlay = JSON.parse(fs.readFileSync(overlayPath, 'utf8'));
const DONE = /^(FIXED|PASS|VERIFIED)$/;
const items = [];
for (const f of fs.readdirSync(dir).filter((x) => /^b\d\d-r2\.json$/.test(x)).sort()) {
  const j = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  for (const it of (Array.isArray(j) ? j : Object.values(j))) {
    if (!it || typeof it !== 'object' || !it.id) continue;
    const r2 = String(it.status || 'NEW').toUpperCase();
    if (DONE.test(r2)) continue;
    items.push({ tester: f.slice(0, 3), id: it.id, replays: it.replays || '', r2, sev: it.severity || '?', area: it.area || '', title: String(it.title || '').replace(/\|/g, '/').replace(/\s+/g, ' ') });
  }
}
const known = new Set(items.map((i) => i.id));
const missing = items.filter((i) => !overlay[i.id]).map((i) => i.id);
const unknown = Object.keys(overlay).filter((k) => !k.startsWith('_') && !known.has(k));
if (process.argv.includes('--check')) {
  if (missing.length || unknown.length) { console.error('missing overlay: ' + missing.join(', ') + '\nunknown ids: ' + unknown.join(', ')); process.exit(1); }
  console.log('ok: ' + items.length + ' items, all have an owner and a status'); process.exit(0);
}
const ORDER = { P0: 0, P1: 1, P2: 2, P3: 3, '?': 4 };
const row = (i) => { const o = overlay[i.id] || { owner: '?', status: 'open', test: '-', note: 'NO OVERLAY ENTRY' }; return Object.assign({}, i, o); };
const rows = items.map(row).sort((a, b) => (ORDER[a.sev] - ORDER[b.sev]) || (a.id < b.id ? -1 : 1));
const count = (pred) => rows.filter(pred).length;
const tally = (sev) => ['open', 'claimed', 'verified', 'decided', 'backlog'].map((s) => s + ' ' + count((r) => r.sev === sev && r.status === s)).join(', ');
const cut = (s, n) => (s.length > n ? s.slice(0, n - 1) + '…' : s);
const out = [];
out.push('# Round 4 triage (D5 QA, generated)');
out.push('');
out.push('Generated by `node game/tools/r4-triage.js` from every `b??-r2.json` item whose round-2 status is not FIXED (NOT FIXED, NEW, NOT RETESTED,');
out.push('PARTIAL, NOT REPRODUCED) plus the hand-kept overlay `round4-status.json` (owner, status, test, note). Edit the overlay, then regenerate.');
out.push('Do not edit this file by hand. Updated: ' + (overlay._updated || '?') + '.');
out.push('');
out.push('Status words: **verified** = D5 replayed it functionally (the named test or replay); **claimed** = a fix commit exists, D5 has not replayed it;');
out.push('**open** = no fix yet; **decided** = closed by an owner decision / documented won\'t-do; **backlog** = moved out of the round by ROUND4.md.');
out.push('"fails before" in a note means the named test was run by D5 against the tree before the fix and went red there.');
out.push('');
out.push('## Counts');
out.push('');
out.push('| Severity | Items | By status |');
out.push('|---|---|---|');
for (const s of ['P0', 'P1', 'P2', 'P3']) out.push('| ' + s + ' | ' + count((r) => r.sev === s) + ' | ' + tally(s) + ' |');
out.push('');
out.push('| Owner | Items | open | claimed | verified | decided / backlog |');
out.push('|---|---|---|---|---|---|');
for (const d of ['D1', 'D2', 'D3', 'D4', 'D5']) out.push('| ' + d + ' | ' + count((r) => r.owner === d) + ' | ' + count((r) => r.owner === d && r.status === 'open') + ' | ' + count((r) => r.owner === d && r.status === 'claimed') + ' | ' + count((r) => r.owner === d && r.status === 'verified') + ' | ' + count((r) => r.owner === d && /decided|backlog/.test(r.status)) + ' |');
out.push('');
for (const s of ['P1', 'P2', 'P3']) {
  const part = rows.filter((r) => r.sev === s);
  if (!part.length) continue;
  out.push('## ' + s + ' (' + part.length + ')');
  out.push('');
  out.push('| Id | Round 2 | Owner | Status | Area: finding | Test / replay | Note |');
  out.push('|---|---|---|---|---|---|---|');
  for (const r of part) out.push('| ' + r.id + (r.replays ? ' (' + r.replays + ')' : '') + ' | ' + r.r2 + ' | ' + r.owner + ' | **' + r.status + '** | ' + cut(r.area, 40) + ': ' + cut(r.title, 150) + ' | ' + (r.test || '-') + ' | ' + (r.note || '') + ' |');
  out.push('');
}
if (overlay._log && overlay._log.length) { out.push('## Update log'); out.push(''); for (const l of overlay._log) out.push('- ' + l); out.push(''); }
fs.writeFileSync(path.join(dir, 'ROUND4-TRIAGE.md'), out.join('\n'));
console.log('wrote ROUND4-TRIAGE.md: ' + rows.length + ' items; missing overlay ' + missing.length + '; unknown ' + unknown.length);
if (missing.length) console.log('missing: ' + missing.join(', '));
