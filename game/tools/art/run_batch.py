#!/usr/bin/env python3
"""Orchestrates one hero batch: master -> action sheets -> process -> validate -> critic hooks -> file into the repo.

  run_batch.py b02 --dry-run        plan + cost estimate only (no network, nothing written)   [the only mode used in the build task]
  run_batch.py b02 --live           run / resume (real calls; stops cleanly at the spend cap)

Resumable: everything is recorded in work/<batch>/ (generate-state.json, run-state.json, per-class critic files). Run the
same command again after the cap was raised, or after the orchestrator ran `critic.py apply`.

Phases per class (printed by every run):
  generate   master + 7 action sheets (+ retry sheets planned by critic.py apply)
  process    raw -> strips under work/<batch>/out/characters/<class>/
  validate   ingest-art-zip.py checks (sizes, alpha 0/255, 4x4 grid, palette, margins, empty frames)
  critic     AWAITING_CRITIC: `critic.py prepare` wrote contact-sheet.png + critic-request.json; the orchestrator runs the
             Sonnet critic, saves work/<batch>/<class>/verdict.json and runs `critic.py apply`
  finalize   when every class is PASS (or has only known_issues): files game/assets/arcane/<id>-<label>/ and updates INDEX.json
"""
import argparse
import datetime
import glob
import json
import os
import shutil
import sys

import common
import critic
import generate
import process
from spec_lib import ACTIONS, DIRS, load_spec

EXIT_OK, EXIT_PAUSED_CAP, EXIT_WAIT, EXIT_BLOCKED = 0, 3, 4, 2


def wdir(batch):
    return os.path.join(common.WORK_DIR, batch)


def latest_raw(batch, cid, kind):
    """Newest generated raw image for a kind (retry sheets have _rN suffixes). Returns (path, attempt) or (None, 0)."""
    best, n_best = None, -1
    for p in glob.glob(os.path.join(wdir(batch), 'raw', cid, '%s_%s_%s*.png' % (batch, cid, kind))):
        b = os.path.basename(p)[:-4]
        tail = b[len('%s_%s_%s' % (batch, cid, kind)):]
        if tail == '':
            n = 0
        elif tail.startswith('_r') and tail[2:].isdigit():
            n = int(tail[2:])
        else:
            continue
        if n > n_best:
            best, n_best = p, n
    return best, max(n_best, 0)


def plan_jobs(cfg, batch):
    """All jobs still missing for the batch: first sheets, plus retry sheets from each class's retry-plan.json."""
    classes = cfg['batches'][batch]['classes']
    jobs = []
    for cid in classes:
        plan = common.read_json(os.path.join(wdir(batch), cid, 'retry-plan.json'))
        have = {k: latest_raw(batch, cid, k)[1] if latest_raw(batch, cid, k)[0] else None for k in ['master'] + ACTIONS}
        missing = [k for k in ['master'] + ACTIONS if have[k] is None]
        if missing:
            jobs += generate.jobs_for(cfg, batch, [cid], missing)
        if plan and plan.get('status') == 'RETRY':
            for r in plan['retries']:
                kind, att = r['kind'], r['attempt']
                if have.get(kind) is not None and have[kind] >= att:
                    continue  # this retry was already generated
                jobs += generate.jobs_for(cfg, batch, [cid], [kind], {'%s/%s' % (cid, kind): r['fix_hints']}, attempt=att)
    return jobs


def process_class(cfg, batch, cid, log):
    """Process every action's newest raw sheet. Returns (entries, issues, errors)."""
    spec = load_spec(cid)
    out = os.path.join(wdir(batch), 'out')
    entries, issues, errors = [], {}, {}
    for a in ACTIONS:
        raw, _ = latest_raw(batch, cid, a)
        if not raw:
            errors[a] = 'no raw sheet yet'
            continue
        try:
            r = process.process_sheet(raw, spec, a, cfg, out)
            entries += r['entries']
            issues.update(r['issues'])
        except ValueError as e:
            errors[a] = str(e)
            log('  %s %s: PROCESS FAILED: %s' % (cid, a, e))
    return entries, issues, errors


def finalize(cfg, batch, entries, class_info, status_note=''):
    """Write game/assets/arcane/<id>-<label>/ and update INDEX.json (never called from --dry-run)."""
    label = cfg['batches'][batch]['label']
    dest = os.path.join(common.ARCANE, '%s-%s' % (batch, label))
    out = os.path.join(wdir(batch), 'out')
    if os.path.exists(dest):
        shutil.rmtree(dest)
    shutil.copytree(os.path.join(out, 'characters'), os.path.join(dest, 'characters'))
    pal = set()
    for cid in cfg['batches'][batch]['classes']:
        pal |= set(v.lower() for v in load_spec(cid)['palette'].values())
    pal = sorted(pal)
    common.write_json(os.path.join(dest, 'palette.json'), {'source': 'class palettes of ' + batch + ' (all from the shared b00+b01 palette)',
                                                          'max_colors': len(pal), 'actual_colors': len(pal), 'colors': pal})
    manifest = {'name': 'Arcane RPG - %s (%d strips) generated by game/tools/art' % (batch.upper(), len(entries)),
                'license': 'original designs, generated with gpt-image-1.5 for the owner', 'frame_size': 256, 'assets': entries}
    common.write_json(os.path.join(dest, 'manifest.json'), manifest)
    known = []
    for cid, info in class_info.items():
        known += info.get('known_issues', [])
    rep = process.validate_entries(dest, entries, pal)
    known.append({'id': '%s_all_attacks' % batch, 'what_is_wrong': 'Muzzle coordinates are computed from weapon-coloured pixels and still need in-engine calibration.'})
    common.write_json(os.path.join(dest, 'known_issues.json'), known)
    status = 'needs-fix' if rep['blocking'] else 'provisional'
    report = {'batch': batch, 'label': label, 'generated_utc': datetime.datetime.utcnow().isoformat() + 'Z', 'files': len(entries),
              'duplicate_ids': 0, 'blocking': rep['blocking'], 'warnings': rep['warnings'], 'standing_heights': rep['standing'],
              'status': status, 'validated_with': rep['used'], 'processing_issues': dict((c, i.get('issues', {})) for c, i in class_info.items())}
    common.write_json(os.path.join(dest, 'validation-report.json'), report)
    with open(os.path.join(dest, 'README.txt'), 'w') as f:
        f.write('Arcane RPG %s (%s)\nGenerated by game/tools/art (gpt-image-1.5, code post-processing). Original designs.\n'
                '%d strips, 256x256 cells, anchor 128,231. %s\n' % (batch.upper(), label, len(entries), status_note))
    ipath = os.path.join(common.ARCANE, 'INDEX.json')
    idx = common.read_json(ipath, {'batches': []})
    idx['batches'] = [b for b in idx['batches'] if b['id'] != batch]
    idx['batches'].append({'id': batch, 'label': label, 'path': 'assets/arcane/%s-%s' % (batch, label),
                           'manifest': 'assets/arcane/%s-%s/manifest.json' % (batch, label), 'files': len(entries), 'status': status,
                           'ingested_utc': report['generated_utc']})
    idx['batches'].sort(key=lambda b: b['id'])
    common.write_json(ipath, idx)
    return dest, status


def run(batch, dry_run=True, live=False, allow_partial=False, out=print):
    cfg = common.load_config()
    if batch not in cfg['batches']:
        out('unknown batch %s (config.json batches: %s)' % (batch, ', '.join(cfg['batches'])))
        return EXIT_BLOCKED
    ledger = common.ledger_path(cfg)
    classes = cfg['batches'][batch]['classes']
    jobs = plan_jobs(cfg, batch)
    out('batch %s (%s): classes %s' % (batch, cfg['batches'][batch]['label'], ', '.join(classes)))
    if dry_run:
        fits, total = generate.print_dry_run(cfg, jobs, ledger, False)
        out('PIPELINE (dry run): generate %d image(s) -> process -> validate (ingest-art-zip checks) -> critic prepare (contact-sheet.png, '
            'critic-request.json) -> [orchestrator: Sonnet critic -> critic.py apply] -> retries (max %d per strip) -> finalize into '
            'game/assets/arcane/%s-%s/ + INDEX.json' % (len(jobs), cfg['retry']['max_per_strip'], batch, cfg['batches'][batch]['label']))
        return EXIT_OK
    transport = generate.make_transport(cfg, live)
    if transport is None:
        out('refusing to run: pass --live for real calls (or --dry-run)')
        return EXIT_BLOCKED
    if jobs:
        fits, total = generate.print_dry_run(cfg, jobs, ledger, False)
        if not fits and not allow_partial:
            out('PAUSED (cap): the pending images (est %.4f USD) do not fit under the stop level. Raise config.json only with the '
                'owner\'s OK, or pass --allow-partial to generate as many as fit.' % total)
            st = common.read_json(os.path.join(wdir(batch), 'run-state.json'), {})
            st['status'] = 'paused_cap'
            common.write_json(os.path.join(wdir(batch), 'run-state.json'), st)
            return EXIT_PAUSED_CAP
        s = generate.run_jobs(jobs, cfg, ledger, os.path.join(wdir(batch), 'generate-state.json'), transport, batch)
        out('generate: %s' % json.dumps({k: s[k] for k in ('status', 'done', 'failed', 'paused_at')}))
        if s['status'] == 'paused_cap':
            return EXIT_PAUSED_CAP
        if s['status'] == 'failed':
            return EXIT_BLOCKED
    waiting, all_entries, class_info = [], [], {}
    for cid in classes:
        entries, issues, errors = process_class(cfg, batch, cid, out)
        cdir = os.path.join(wdir(batch), cid)
        plan = common.read_json(os.path.join(cdir, 'retry-plan.json'))
        if errors:
            out('  %s: not processable yet: %s' % (cid, json.dumps(errors)))
            waiting.append(cid)
            continue
        rep = process.validate_entries(os.path.join(wdir(batch), 'out'), entries, set(load_spec(cid)['palette'].values()))
        out('  %s: %d strips, validation blocking=%d warnings=%d (%s)' % (cid, len(entries), len(rep['blocking']), len(rep['warnings']), rep['used']))
        class_info[cid] = dict(issues=issues, blocking=rep['blocking'], known_issues=(plan or {}).get('known_issues', []))
        # a verdict is current only if no newer sheet was generated after the plan asked for a retry
        pending_retry = plan and plan.get('status') == 'RETRY'
        if plan is None or pending_retry:
            critic.prepare(batch, cid)
            if pending_retry:
                # retries were generated and processed above: archive the old verdict, ask the critic again
                n = len(glob.glob(os.path.join(cdir, 'qa-verdict.*.json'))) + 1
                shutil.move(os.path.join(cdir, 'qa-verdict.json'), os.path.join(cdir, 'qa-verdict.%d.json' % n))
                os.remove(os.path.join(cdir, 'retry-plan.json'))
            out('  %s: AWAITING_CRITIC -> %s' % (cid, os.path.join(cdir, 'critic-request.json')))
            waiting.append(cid)
            continue
        all_entries += entries
    if waiting:
        common.write_json(os.path.join(wdir(batch), 'run-state.json'), {'status': 'awaiting_critic', 'classes': waiting})
        out('WAITING: critic needed for %s. Then: critic.py apply work/%s/<class>/verdict.json and re-run this command.' % (', '.join(waiting), batch))
        return EXIT_WAIT
    if any(i['blocking'] for i in class_info.values()):
        out('BLOCKING validation problems remain; filing as needs-fix')
    dest, status = finalize(cfg, batch, all_entries, class_info)
    common.write_json(os.path.join(wdir(batch), 'run-state.json'), {'status': 'done', 'dest': dest})
    out('filed %d strips to %s (status %s)' % (len(all_entries), dest, status))
    return EXIT_OK


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('batch')
    ap.add_argument('--dry-run', action='store_true')
    ap.add_argument('--live', action='store_true')
    ap.add_argument('--allow-partial', action='store_true')
    a = ap.parse_args(argv)
    dry = a.dry_run or not (a.live or os.environ.get('ART_HTTP_MOCK'))
    if dry and not a.dry_run:
        print('(no --live flag: behaving as --dry-run)')
    return run(a.batch, dry_run=dry, live=a.live, allow_partial=a.allow_partial)


if __name__ == '__main__':
    sys.exit(main())
