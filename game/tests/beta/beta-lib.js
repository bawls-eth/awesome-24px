// Pure helpers for the beta gate (no Playwright needed): geometry, thresholds, report writer.
'use strict';
const fs = require('fs');
const path = require('path');

// Rects are {x,y,w,h}. Overlap only counts when the intersection is more than `tol` px in both axes.
function intersect(a, b) {
  const w = Math.min(a.x + a.w, b.x + b.w) - Math.max(a.x, b.x);
  const h = Math.min(a.y + a.h, b.y + b.h) - Math.max(a.y, b.y);
  return w > 0 && h > 0 ? { w, h } : null;
}
function rectsOverlap(a, b, tol = 2) { const i = intersect(a, b); return !!i && i.w > tol && i.h > tol; }
// hud / ctrl: arrays of {sel, x, y, w, h}; returns [{hud, ctrl, w, h}]
function findOverlaps(hud, ctrl, tol = 2) {
  const out = [];
  for (const a of hud) for (const b of ctrl) {
    if (a.sel === b.sel) continue;
    if ((a.nest && a.nest.includes(b.sel)) || (b.nest && b.nest.includes(a.sel))) continue; // DOM-nested: not an overlap
    const i = intersect(a, b);
    if (i && i.w > tol && i.h > tol) out.push({ hud: a.sel, ctrl: b.sel, w: Math.round(i.w), h: Math.round(i.h) });
  }
  return out;
}
// items: [{sel,x,y,w,h}]; returns those smaller than min x min (the collector only passes visible ones)
function tapOffenders(items, min = 40) {
  return items.filter((r) => r.w > 0 && r.h > 0 && (r.w < min - 0.5 || r.h < min - 0.5)).map((r) => ({ sel: r.sel, w: Math.round(r.w), h: Math.round(r.h) }));
}
function scrollOk(m) { return m.sw <= m.cw + 1 && m.bw <= m.cw + 1; }

// Verdict for one page+viewport result. fps thresholds: <30 fail, 30-40 warn.
function judge(r, opts = {}) {
  const fails = [], warns = [];
  const minFps = opts.minFps || 30, warnFps = opts.warnFps || 40;
  if (r.loadError) fails.push('load: ' + r.loadError);
  if (r.errors && r.errors.length) fails.push(r.errors.length + ' console/page error(s)');
  if (r.failedReqs && r.failedReqs.length) fails.push(r.failedReqs.length + ' failed request(s)');
  if (typeof r.avgFps === 'number') { if (r.avgFps < minFps) fails.push('avg fps ' + r.avgFps.toFixed(1) + ' < ' + minFps); else if (r.avgFps < warnFps) warns.push('avg fps ' + r.avgFps.toFixed(1) + ' (target ' + warnFps + '+)'); }
  if (r.scroll && !scrollOk(r.scroll)) fails.push('horizontal scroll');
  if (r.phone && r.tapOffenders && r.tapOffenders.length) fails.push(r.tapOffenders.length + ' tap target(s) < 40px');
  if (r.overlaps && r.overlaps.length) fails.push(r.overlaps.length + ' HUD/control overlap(s)');
  if (r.clipped && r.clipped.length) fails.push(r.clipped.length + ' clipped text element(s)');
  if (r.back && r.back.ok === false) fails.push('back link: ' + r.back.why);
  if (r.save && r.save.ok === false) fails.push('save round trip: ' + r.save.why);
  if (typeof r.longFrames === 'number' && r.longFrames > 40) warns.push(r.longFrames + ' long frames');
  return { pass: fails.length === 0, fails, warns };
}

const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
function pstString(d) { return d.toLocaleString('en-US', { timeZone: 'America/Los_Angeles', hour12: false, year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit' }) + ' Pacific'; }

function buildReport(results, meta) {
  const now = meta.now || new Date();
  const pages = [];
  const order = [];
  for (const r of results) { if (!order.includes(r.page)) order.push(r.page); }
  for (const p of order) {
    const rows = results.filter((r) => r.page === p).map((r) => ({ ...r, verdict: judge(r) }));
    pages.push({
      page: p, url: rows[0] && rows[0].url, pass: rows.every((x) => x.verdict.pass),
      viewports: rows.map((x) => ({ viewport: x.viewport, phone: !!x.phone, pass: x.verdict.pass, fails: x.verdict.fails, warns: x.verdict.warns, avgFps: x.avgFps, worstFrameMs: x.worstFrameMs, longFrames: x.longFrames, errors: x.errors || [], failedReqs: x.failedReqs || [], scroll: x.scroll, tapOffenders: x.tapOffenders || [], overlaps: x.overlaps || [], clipped: x.clipped || [], back: x.back, save: x.save, notes: x.notes || [], screens: x.screens || {} })),
    });
  }
  const green = pages.length > 0 && pages.every((p) => p.pass);
  const json = { generated_utc: now.toISOString(), commit: meta.commit || 'unknown', green, pages };
  const L = [];
  L.push('# Beta report (generated)');
  L.push('');
  L.push('Generated by `node game/tests/run-all.js --beta` (game/tests/beta/beta-run.js). The tables are regenerated each run; the "What looks off" section is hand-written and kept.');
  L.push('');
  L.push(`- Generated: ${now.toISOString()} (UTC) / ${pstString(now)}`);
  L.push(`- Commit: \`${meta.commit || 'unknown'}\``);
  const nFail = pages.filter((p) => !p.pass).length;
  L.push(`- **Summary: ${green ? 'GREEN' : 'RED'}** (${pages.length - nFail}/${pages.length} pages pass${nFail ? '; failing: ' + pages.filter((p) => !p.pass).map((p) => p.page).join(', ') : ''})`);
  L.push('- Thresholds: zero console/page errors, zero failed requests, avg fps >= 30 (warn 30-40, target 40+, headless software rendering), no horizontal scroll, phone tap targets >= 40x40, no HUD/control overlap, no clipped HUD text, back link works, save round trip survives reload.');
  L.push('');
  for (const p of pages) {
    L.push(`## ${p.page} - ${p.pass ? 'PASS' : 'FAIL'}`);
    L.push('');
    L.push('| Viewport | Result | Avg fps | Worst frame | Long frames | Errors | Failed req | Scroll | Tap <40px | Overlap | Clip | Back | Save | Screens |');
    L.push('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|');
    for (const v of p.viewports) {
      const sc = ['start', 'mid', 'end'].filter((k) => v.screens[k]).map((k) => `[${k}](${v.screens[k]})`).join(' ');
      const fps = typeof v.avgFps === 'number' ? v.avgFps.toFixed(1) + (v.avgFps < 30 ? ' (FAIL)' : v.avgFps < 40 ? ' (warn)' : '') : 'n/a';
      const tap = v.tapOffenders.length ? esc(v.tapOffenders.length + ': ' + v.tapOffenders.slice(0, 4).map((t) => `${t.sel} ${t.w}x${t.h}`).join('; ')) : (v.phone ? '0' : 'n/a');
      L.push(`| ${v.viewport} | ${v.pass ? 'pass' : 'FAIL'} | ${fps} | ${typeof v.worstFrameMs === 'number' ? Math.round(v.worstFrameMs) + ' ms' : 'n/a'} | ${v.longFrames == null ? 'n/a' : v.longFrames} | ${v.errors.length} | ${v.failedReqs.length} | ${v.scroll ? (scrollOk(v.scroll) ? 'ok' : 'SCROLL ' + v.scroll.sw + '>' + v.scroll.cw) : 'n/a'} | ${tap} | ${v.overlaps.length ? esc(v.overlaps.map((o) => `${o.hud}x${o.ctrl}`).join('; ')) : '0'} | ${v.clipped.length ? esc(v.clipped.slice(0, 3).join('; ')) : '0'} | ${v.back ? (v.back.ok ? 'ok' : 'FAIL') : 'n/a'} | ${v.save ? (v.save.ok ? 'ok' : 'FAIL') : 'n/a'} | ${sc} |`);
    }
    const notes = [];
    for (const v of p.viewports) {
      for (const n of (v.notes || [])) notes.push(`- ${v.viewport}: note ${esc(n)}`);
      for (const f of v.fails) notes.push(`- ${v.viewport}: FAIL ${esc(f)}`);
      for (const w of v.warns) notes.push(`- ${v.viewport}: warn ${esc(w)}`);
      for (const e of v.errors.slice(0, 5)) notes.push(`- ${v.viewport}: error \`${esc(e).slice(0, 220)}\``);
      for (const e of v.failedReqs.slice(0, 5)) notes.push(`- ${v.viewport}: failed request \`${esc(e).slice(0, 220)}\``);
      if (v.tapOffenders.length > 4) notes.push(`- ${v.viewport}: all tap offenders: ${esc(v.tapOffenders.map((t) => `${t.sel} ${t.w}x${t.h}`).join('; '))}`);
      if (v.clipped.length > 3) notes.push(`- ${v.viewport}: all clipped: ${esc(v.clipped.join('; '))}`);
    }
    if (notes.length) { L.push(''); L.push(...notes); }
    L.push('');
  }
  L.push('## What looks off');
  L.push('');
  L.push(meta.whatLooksOff || '(written by hand after viewing the screenshots)');
  L.push('');
  return { md: L.join('\n'), json };
}

// Writes BETA-REPORT.md + beta-status.json into designDir. The hand-written "What looks off" section of an
// existing report is kept when meta.whatLooksOff is not given.
function writeReport(results, meta, designDir) {
  const mdPath = path.join(designDir, 'BETA-REPORT.md');
  if (!meta.whatLooksOff && fs.existsSync(mdPath)) {
    const old = fs.readFileSync(mdPath, 'utf8');
    const i = old.indexOf('## What looks off');
    if (i >= 0) { const t = old.slice(i + '## What looks off'.length).trim(); if (t && !t.startsWith('(written by hand')) meta = { ...meta, whatLooksOff: t }; }
  }
  const { md, json } = buildReport(results, meta);
  fs.mkdirSync(designDir, { recursive: true });
  fs.writeFileSync(mdPath, md);
  fs.writeFileSync(path.join(designDir, 'beta-status.json'), JSON.stringify(json, null, 2) + '\n');
  return json;
}

module.exports = { intersect, rectsOverlap, findOverlaps, tapOffenders, scrollOk, judge, buildReport, writeReport, pstString };
